DEF_TEST(parseUfsSamsungHealthDescr) {
  uint8_t u8InqBuff[36] = {0};
  uint8_t uDescrHealthReportBuf[45] = {0};
  int res = 0;
  const int expected = 36;
  res = testReadSamsungUFSProductInfo(u8InqBuff, 36);
  EXPECT_EQ_INT(expected, res);
  res = memstr(u8InqBuff, "SAMSUNG", sizeof(u8InqBuff));
  EXPECT_EQ_INT(0, res);
  res = testReadSamsungUFSHealthDescriptorInfo(uDescrHealthReportBuf, 45);
  EXPECT_EQ_INT(45, res);
  struct samsungHealthDescFields3_1 samsungData;
  parseUfsSamsungHealthDescr(uDescrHealthReportBuf, &samsungData);
  EXPECT_EQ_INT(45, samsungData.bLength);
  EXPECT_EQ_INT(9, samsungData.bDescriptorType);
  return 0;
}


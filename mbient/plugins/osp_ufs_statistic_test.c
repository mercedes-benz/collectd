  int res = 0;
  const int expected = 36;
  res = testReadMicronUFSProductInfo(u8InqBuff, 36);
  EXPECT_EQ_INT(expected, res);
  res = memstr(u8InqBuff, "MICRON", sizeof(u8InqBuff));
  EXPECT_EQ_INT(0, res);
  res = testReadUFSHealthReportMicron(uHealthReportBuf, 512);
